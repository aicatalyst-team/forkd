# --- Scenario 3: invalid-sandbox-request ---
def validate_404_error(status, body):
    """Validate that we get a proper error response for a non-existent sandbox."""
    if status != 404:
        return False, f"Expected 404, got {status}"
    # Check that response is valid JSON (error body)
    try:
        data = json.loads(body)
        return True, None
    except json.JSONDecodeError:
        # Even if not JSON, a 404 is still correct behavior
        return True, None

test_scenario(
    name="invalid-sandbox-request",
    description="GET a non-existent sandbox to verify error handling returns 404",
    method="GET",
    path="/v1/sandboxes/nonexistent-id",
    expected_status=404,
    validate_fn=validate_404_error,
    timeout=15,
)

# --- Scenario 4: create-sandbox-no-kvm ---
def validate_create_error(status, body):
    """Validate that sandbox creation fails gracefully without KVM."""
    # We accept any 4xx or 5xx as valid since KVM is not available
    if 400 <= status < 600:
        # Check that we got some response body (not a crash/empty response)
        if len(body.strip()) > 0:
            return True, None
        else:
            return False, "Empty error response body - controller might have crashed"
    return False, f"Expected 4xx or 5xx, got {status}"

test_scenario(
    name="create-sandbox-no-kvm",
    description="Attempt POST to create sandbox without KVM; should fail gracefully",
    method="POST",
    path="/v1/sandboxes",
    body={"snapshot": "test", "id": "poc-test"},
    expected_status=list(range(400, 600)),
    validate_fn=validate_create_error,
    timeout=30,
)

# After scenario 4, verify the controller is still alive by hitting health endpoint again
test_scenario(
    name="post-create-health-check",
    description="Verify controller is still healthy after failed sandbox creation (did not crash)",
    method="GET",
    path="/v1/sandboxes",
    expected_status=200,
    validate_fn=validate_sandboxes_list,
    timeout=15,
)

# ========== END SCENARIOS ==========

# Output results as JSON
print(json.dumps({"results": results}, indent=2))

# Exit with appropriate code
failed = any(r["status"] in ("fail", "error") for r in results)
sys.exit(1 if failed else 0)
